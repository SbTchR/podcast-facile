import assert from 'node:assert/strict';
import { typescriptModuleUrl, loadAudioEngine } from './audio-test-module.mjs';
import { resolveSectionLayers } from '../src/audio/sectionLayers.ts';
const { voiceSplitPoint, splitVoice, removeVoicePiece } = await import(await typescriptModuleUrl(new URL('../src/audio/voiceEditing.ts', import.meta.url)));
const { getTimeline, getProjectDuration } = await loadAudioEngine();
const close = (a, b, why) => assert.ok(Math.abs(a - b) < 1e-6, why ?? `${a} ≠ ${b}`);
const block = { id: 'voice', sectionId: 'part', title: 'Mon texte', type: 'voice', assetId: 'original', trimStart: 2, trimEnd: 12, duration: 10, volume: 'normal', fadeIn: 'normal', fadeOut: 'short', voiceEffect: 'none', script: 'Le texte original.' };
const music = { id: 'music', kind: 'music', title: 'Fond', assetId: 'bed', sourceStart: 0, sourceEnd: 20, start: { edge: 'start' }, end: { edge: 'end' }, volume: 32, repeat: true, fadeIn: 'short', fadeOut: 'short' };
const sfx = { ...music, id: 'sfx', kind: 'sfx', repeat: false, sourceEnd: 1, start: { blockId: 'voice', edge: 'start', seconds: 7 }, end: { blockId: 'voice', edge: 'start', seconds: 8 } };
const other = { ...block, id: 'other', sectionId: 'other' };
const project = { id: 'test', sections: [{ id: 'part', title: 'Partie', audioLayers: [music, sfx] }, { id: 'other', title: 'Autre partie' }], blocks: [block, other], assets: [{ id: 'original', duration: 14 }, { id: 'bed', duration: 20 }] };
const before = JSON.stringify(project);
for (const at of [0, .05, 9.99, 10, NaN]) assert.equal(voiceSplitPoint(project, 'voice', at), undefined, 'Cuts stay away from the excerpt boundaries.');
let edited = splitVoice(project, 'voice', 3, 'right');
assert.equal(JSON.stringify(project), before, 'Editing never mutates the source project or its assets.');
assert.equal(edited.assets, project.assets);
assert.equal(edited.sections[1], project.sections[1]);
assert.equal(edited.blocks.at(-1), other);
assert.deepEqual(edited.blocks.slice(0, 2).map(b => [b.assetId, b.trimStart, b.trimEnd]), [['original', 2, 5], ['original', 5, 12]]);
assert.equal(edited.blocks[0].fadeIn, 'normal');
assert.equal(edited.blocks[0].voiceCutEnd, true);
assert.equal(edited.blocks[1].voiceCutStart, true);
assert.equal(edited.blocks[1].fadeOut, 'short');
assert.equal(edited.blocks[1].script, block.script);
close(getProjectDuration(edited), getProjectDuration(project), 'A split never lengthens or shortens a part.');
let placement = resolveSectionLayers(edited, getTimeline(edited)).find(item => item.layer.id === 'sfx');
close(placement.start, 7); close(placement.end, 8);
assert.equal(placement.layer.start.blockId, 'right', 'Sounds follow the appropriate split fragment.');
edited = splitVoice(edited, 'right', 6, 'last');
assert.deepEqual(edited.blocks.slice(0, 3).map(b => [b.trimStart, b.trimEnd]), [[2, 5], [5, 8], [8, 12]]);
edited = removeVoicePiece(edited, 'right');
assert.deepEqual(edited.blocks.slice(0, 2).map(b => [b.trimStart, b.trimEnd]), [[2, 5], [8, 12]], 'Two cuts remove only the selected middle source interval.');
close(getProjectDuration(edited), getProjectDuration(project) - 3);
placement = resolveSectionLayers(edited, getTimeline(edited)).find(item => item.layer.id === 'sfx');
close(placement.start, 4); close(placement.end, 5);
const bed = resolveSectionLayers(edited, getTimeline(edited)).find(item => item.layer.id === 'music');
close(bed.end, 7, 'A full-part bed follows the shortened part.');
assert.equal(edited.blocks.at(-1), other);
for (const [effect, rate] of [['deep', .9], ['high', 1.12], ['very-high', 1.24]]) {
  const altered = { ...project, blocks: [{ ...block, voiceEffect: effect }, other] };
  const split = splitVoice(altered, 'voice', 3 / rate, 'right');
  close(split.blocks[0].trimEnd, 5, 'Cut positions respect voice speed.');
  close(getProjectDuration(split), getProjectDuration(altered));
}
const legacy = { ...project, blocks: [{ ...block, voiceEffect: 'high', background: { assetId: 'bed', level: 'low', startBefore: true, startBeforeSeconds: 2, continueAfter: true, continueAfterSeconds: 3 }, voiceCues: [{ id: 'cue', assetId: 'bed', at: 2, sourceStart: 5, sourceEnd: 9, duration: 4, level: 'normal' }] }, other] };
const legacyCut = 2 + 4 / 1.12;
const legacySplit = splitVoice(legacy, 'voice', legacyCut, 'right');
close(getProjectDuration(legacySplit), getProjectDuration(legacy), 'Legacy music lead and tail are counted once.');
assert.equal(legacySplit.blocks[0].background.continueAfter, false);
assert.equal(legacySplit.blocks[1].background.startBefore, false);
close(legacySplit.blocks[1].background.sourceOffsetSeconds, legacyCut, 'A legacy background continues from the same music position.');
const [leftCue, rightCue] = legacySplit.blocks.slice(0, 2).map(b => b.voiceCues[0]);
close(leftCue.sourceEnd, rightCue.sourceStart, 'A sound crossing the cut continues without lost or repeated samples.');
close(leftCue.duration + rightCue.duration, 4);
assert.equal(leftCue.cutEnd, true);
close(rightCue.at, 0);
assert.equal(voiceSplitPoint(legacy, 'voice', 1), undefined, 'Do not split the music-only lead.');
const gap = { ...block, id: 'gap', type: 'silence', duration: 1, trimStart: 0, trimEnd: 0 };
const paused = { ...project, blocks: [block, gap, other], sections: [{ ...project.sections[0], audioLayers: [{ ...sfx, pauseBlockId: 'gap', afterBlockId: 'voice', start: { blockId: 'gap', edge: 'start' }, end: { blockId: 'gap', edge: 'end' } }] }, project.sections[1]] };
const pausedSplit = splitVoice(paused, 'voice', 3, 'right');
assert.equal(pausedSplit.sections[0].audioLayers[0].afterBlockId, 'right', 'A dedicated sound pause stays after both pieces.');
const deleted = removeVoicePiece(pausedSplit, 'right');
assert.equal(deleted.sections[0].audioLayers[0].afterBlockId, 'voice');
assert.equal(resolveSectionLayers(deleted, getTimeline(deleted)).length, 1);
const inside = { ...sfx, start: { blockId: 'voice', edge: 'start', seconds: 4 }, end: { blockId: 'voice', edge: 'start', seconds: 5 } };
const insideProject = { ...project, sections: [{ ...project.sections[0], audioLayers: [music, inside] }, project.sections[1]] };
const insideSplit = splitVoice(splitVoice(insideProject, 'voice', 3, 'right'), 'right', 6, 'last');
const insideDeleted = removeVoicePiece(insideSplit, 'right');
assert.deepEqual(insideDeleted.sections[0].audioLayers.map(layer => layer.id), ['music'], 'Collapsed tracks do not prevent saving the shortened part.');
assert.equal(insideDeleted.assets, project.assets, 'All source sounds remain available for undo.');
console.log('Voice editing: exact source intervals, speed, music/sound anchors, legacy cues, direct inner joins, pause links and isolated non-destructive changes verified.');
