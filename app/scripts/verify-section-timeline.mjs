import assert from 'node:assert/strict';
import { typescriptModuleUrl, loadAudioEngine } from './audio-test-module.mjs';
import { resolveSectionLayers, putSectionLayer } from '../src/audio/sectionLayers.ts';
const { scopeSection, applySectionArrangement, anchorAtTime, editLayerOnTimeline } = await import(await typescriptModuleUrl(new URL('../src/audio/sectionTimeline.ts', import.meta.url)));
const { getTimeline } = await loadAudioEngine();
const voice = (id, sectionId = 'part', duration = 5) => ({ id, sectionId, title: id, type: 'voice', trimStart: 0, trimEnd: duration, duration, voiceEffect: 'none' });
const clip = { id: 'music', kind: 'music', title: 'Musique', assetId: 'bed', sourceStart: 2, sourceEnd: 6, start: { blockId: 'a', edge: 'start', seconds: 1 }, end: { blockId: 'a', edge: 'end' }, repeat: false, volume: 32, fadeIn: 'short', fadeOut: 'short' };
const other = voice('untouched', 'other');
const project = { sections: [{ id: 'part', title: 'Partie', audioLayers: [clip] }, { id: 'other', title: 'Autre partie', audioLayers: [] }], blocks: [voice('a'), voice('b'), other], assets: [{id:'bed',duration:20}] };
let part = scopeSection(project, 'part');
const timeline = getTimeline(part);
assert.deepEqual(anchorAtTime(timeline, 5), { blockId:'b',edge:'start',seconds:0 });
assert.deepEqual(anchorAtTime(timeline, 5, true), { blockId:'a',edge:'end' });
assert.deepEqual(anchorAtTime(timeline, 10, true), { edge:'end' });
assert.deepEqual(anchorAtTime(timeline, -5), { edge:'start' });
const resolve = layer => resolveSectionLayers({...part,sections:[{...part.sections[0],audioLayers:[layer]}]},timeline)[0];
let changed = editLayerOnTimeline(part, clip, 'move', 4);
assert.deepEqual([resolve(changed).start,resolve(changed).end,changed.sourceStart,changed.sourceEnd],[4,8,2,6],'Moving preserves the source excerpt and duration.');
changed = editLayerOnTimeline(part, clip, 'move', 99);
assert.deepEqual([resolve(changed).start,resolve(changed).end],[6,10],'Moves stay inside the current part.');
changed = editLayerOnTimeline(part, clip, 'start', 2);
assert.deepEqual([resolve(changed).start,resolve(changed).end,changed.sourceStart,changed.sourceEnd],[2,5,3,6],'Left trim must trim the source, without shifting its right edge.');
changed = editLayerOnTimeline(part, clip, 'end', 8);
assert.deepEqual([resolve(changed).start,resolve(changed).end,changed.sourceStart,changed.sourceEnd],[1,8,2,9],'Right extension uses available source audio.');
const repeated = {...clip,repeat:true,end:{edge:'end'}};
part = {...part,sections:[{...part.sections[0],audioLayers:[repeated]}]};
changed = editLayerOnTimeline(part, repeated, 'start', 3);
assert.deepEqual([resolve(changed).start,resolve(changed).end,changed.sourceStart,changed.sourceEnd],[3,10,2,6],'Loop boundaries change coverage without cutting the repeated source.');
const order = {...part,sections:[{...part.sections[0],audioLayers:[clip,{...clip,id:'second'}]}]};
putSectionLayer(order,'part',{...clip,volume:40},null);
assert.deepEqual(order.sections[0].audioLayers.map(layer=>layer.id),['music','second'],'Editing a track must not reorder the other lanes.');
const scoped = scopeSection(project,'part');
assert.equal(scoped.blocks.length,2);
assert.equal(scoped.sections.length,1);
const otherSection = project.sections[1];
const oldAssets = project.assets;
const edited = {...scoped,blocks:[...scoped.blocks,{...voice('gap'),type:'silence',duration:1,trimEnd:0}],sections:[{...scoped.sections[0],audioLayers:[changed]}]};
applySectionArrangement(project,edited,'part');
assert.equal(project.sections[1],otherSection,'Other section metadata remains untouched.');
assert.equal(project.blocks.at(-1),other,'Other recordings remain untouched.');
assert.equal(project.assets,oldAssets,'Arrangement commits retain all audio assets.');
assert.equal(project.blocks.filter(block=>block.sectionId==='part').length,3);
console.log('Part timeline: boundary anchors, moves, trims, loops, stable lanes and isolated arrangement commits verified.');
