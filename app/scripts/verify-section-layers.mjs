import assert from 'node:assert/strict';
import { loadAudioEngine } from './audio-test-module.mjs';
import { putSectionLayer, removeSectionLayer, resolveSectionLayers, syncLayerPauses } from '../src/audio/sectionLayers.ts';
import { makeSignatureFx, STUDIO_STYLES, studioVoiceGain } from '../src/audio/jingleStudio.ts';
const { getTimeline, getProjectDuration } = await loadAudioEngine();
const block = (id, duration = 4) => ({ id, sectionId: 'part', title: id, type: 'voice', duration, trimStart: 0, trimEnd: duration, voiceEffect: 'none' });
const project = { sections: [{ id: 'part', title: 'Partie' }], blocks: [block('a'), block('b', 6)], assets: [{ id: 'music', duration: 20 }, { id: 'sfx', duration: 2 }] };
const music = { id: 'bed', kind: 'music', title: 'Fond', assetId: 'music', sourceStart: 3, sourceEnd: 5, start: { edge: 'start' }, end: { edge: 'end' }, volume: 32, fadeIn: 'normal', fadeOut: 'normal', repeat: true };
putSectionLayer(project, 'part', music, null);
let layers = resolveSectionLayers(project, getTimeline(project));
assert.deepEqual([layers[0].start, layers[0].end, layers[0].sourceStart, layers[0].sourceEnd], [0, 10, 3, 5]);
const cue = { ...music, id: 'cue', kind: 'sfx', assetId: 'sfx', sourceStart: 0.5, sourceEnd: 1.5, start: { blockId: 'b', edge: 'start', seconds: 2 }, end: undefined, repeat: false };
putSectionLayer(project, 'part', cue, null);
assert.equal(resolveSectionLayers(project, getTimeline(project))[1].start, 6);
project.blocks.reverse();
assert.equal(resolveSectionLayers(project, getTimeline(project))[1].start, 2, 'Cue must follow the recording when reordered.');
putSectionLayer(project, 'part', cue, 'b');
assert.equal(getProjectDuration(project), 11, 'Between-recording cue must reserve exactly its excerpt length.');
assert.equal(project.blocks[1].type, 'silence');
assert.deepEqual(resolveSectionLayers(project, getTimeline(project)).map(item => [item.start,item.end]), [[0,11],[6,7]]);
putSectionLayer(project, 'part', { ...cue, sourceEnd: 2 }, 'a');
assert.equal(getProjectDuration(project), 11.5, 'Editing a between-voice cue replaces its gap instead of accumulating gaps.');
assert.equal(project.blocks.filter(item => item.type === 'silence').length, 1);
const ownedGap = project.blocks.find(item => item.type === 'silence');
project.blocks = [project.blocks.find(item=>item.id==='a'), project.blocks.find(item=>item.id==='b'), ownedGap];
syncLayerPauses(project);
assert.equal(project.blocks[1].id, ownedGap.id, 'Owned gap must follow its anchor when recordings move.');
removeSectionLayer(project, 'part', 'cue');
assert.equal(getProjectDuration(project), 10);
putSectionLayer(project, 'part', cue, null);
project.blocks = project.blocks.filter(item => item.id !== 'b');
assert.equal(resolveSectionLayers(project, getTimeline(project)).length, 1, 'Deleted anchor must leave a visible unplaced cue, without unexpected playback.');
const ctx = { sampleRate: 44100, createBuffer(channels, frames, rate) { const data = Array.from({length:channels},()=>new Float32Array(frames)); return { duration: frames/rate, getChannelData: channel=>data[channel] }; } };
const fingerprints = new Set();
for (const style of Object.keys(STUDIO_STYLES)) {
 const fx = makeSignatureFx(ctx, style); const repeated = makeSignatureFx(ctx, style);
 assert.deepEqual(fx.getChannelData(0), repeated.getChannelData(0), 'FX exports must be deterministic.');
 const data = fx.getChannelData(0);
 assert.ok(data.every(Number.isFinite));
 assert.ok(Math.max(...data.subarray(0, 10000).map(Math.abs)) < 1, 'FX must leave headroom.');
 assert.ok(data.some(value=>Math.abs(value) > 0.01), 'Each signature must be audible.');
 fingerprints.add(`${fx.duration}:${data[2000]}:${data[6000]}`);
}
assert.equal(fingerprints.size, 6, 'All six styles need distinct FX signatures.');
const spoken = [new Float32Array(4096).fill(0.07), new Float32Array(4096).fill(0.04)];
spoken[1][17] = 0.95;
const spokenGain = studioVoiceGain({ numberOfChannels: 2, getChannelData: channel => spoken[channel] });
assert.ok(spokenGain * 0.95 <= 0.420001, 'A loud consonant in either stereo channel must retain EQ headroom.');
const quietGain = studioVoiceGain({ numberOfChannels: 1, getChannelData: () => new Float32Array(4096).fill(0.02) });
assert.ok(quietGain > 1 && quietGain <= 4, 'Quiet announcements must still be brought up to an audible level.');
console.log('Section layers: anchors, excerpts, gaps, edits, deletion, six deterministic FX and spoken-voice headroom verified.');
